Triples toTriples(const std::vector<double>& flat) {
    if (flat.size() % 3 != 0) throw std::invalid_argument("chromosome length must be a multiple of 3");
    Triples triples;
    triples.reserve(flat.size() / 3);
    for (std::size_t i = 0; i < flat.size(); i += 3) triples.push_back({flat[i], flat[i + 1], flat[i + 2]});
    return triples;
}

std::vector<double> toFlat(const Triples& triples) {
    std::vector<double> flat;
    flat.reserve(triples.size() * 3);
    for (const Triple& t : triples) flat.insert(flat.end(), t.begin(), t.end());
    return flat;
}

